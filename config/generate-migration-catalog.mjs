import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

/**
 * Generate `src/browser/migration-catalog.generated.ts` from the committed
 * drizzle migration folders. The browser adapter cannot read migration files
 * from disk, so the catalog is embedded at build time. Entries mirror what
 * `readMigrationFiles` from `drizzle-orm/migrator` produces for the Node
 * migrator (same statement splitting, same whole-file sha256 hash, same
 * journal timestamps), which keeps `__drizzle_migrations` bookkeeping
 * identical across the Node and browser adapters.
 */

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

/**
 * Read one drizzle migration folder into catalog entries.
 * @param {string} folder - Migration folder relative to the package root.
 * @returns {Array<{ hash: string, folderMillis: number, statements: string[] }>} Catalog entries in journal order.
 */
function readMigrationFolder (folder) {
  const journalPath = path.join(packageRoot, folder, 'meta/_journal.json')
  const journal = JSON.parse(readFileSync(journalPath, 'utf8'))
  return journal.entries.map((entry) => {
    const sql = readFileSync(path.join(packageRoot, folder, `${entry.tag}.sql`), 'utf8')
    return {
      hash: createHash('sha256').update(sql).digest('hex'),
      folderMillis: entry.when,
      statements: sql.split('--> statement-breakpoint'),
    }
  })
}

const chain = readMigrationFolder('drizzle/chain')
const wallet = readMigrationFolder('drizzle/wallet')

const output = `// Generated by config/generate-migration-catalog.mjs. Do not edit.
import type { MigrationEntry } from './migrations.js'

const chainMigrations: MigrationEntry[] = ${JSON.stringify(chain, null, 2)}

const walletMigrations: MigrationEntry[] = ${JSON.stringify(wallet, null, 2)}

export { chainMigrations, walletMigrations }
`

writeFileSync(path.join(packageRoot, 'src/browser/migration-catalog.generated.ts'), output)
